import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { Resvg } from "@resvg/resvg-js";
import { getOctagonalGeometry } from "../../ui/common/src/hud/octagonal-panel/geometry";

const size = 64;
const horizontalPadding = 8;
const verticalPadding = 16;
const radius = 8;
const vertices = getOctagonalGeometry(
    size - 2 * horizontalPadding,
    size - 2 * verticalPadding,
    "sm",
)
    .points.split(" ")
    .map((point) =>
        point
            .split(",")
            .map(
                (coordinate, index) =>
                    Number(coordinate) +
                    (index === 0 ? horizontalPadding : verticalPadding),
            ),
    );
const pixels: string[] = [];

for (let vertical = 0; vertical < size; vertical++) {
    for (let horizontal = 0; horizontal < size; horizontal++) {
        const x = horizontal + 0.5;
        const y = vertical + 0.5;
        let distance = Infinity;
        let inside = true;
        for (const [index, start] of vertices.entries()) {
            const end = vertices[(index + 1) % vertices.length];
            const edgeX = end[0] - start[0];
            const edgeY = end[1] - start[1];
            const fraction = Math.max(
                0,
                Math.min(
                    1,
                    ((x - start[0]) * edgeX + (y - start[1]) * edgeY) /
                        (edgeX * edgeX + edgeY * edgeY),
                ),
            );
            distance = Math.min(
                distance,
                Math.hypot(
                    x - start[0] - fraction * edgeX,
                    y - start[1] - fraction * edgeY,
                ),
            );
            inside &&= edgeX * (y - start[1]) - edgeY * (x - start[0]) >= 0;
        }
        const alpha = Math.max(
            0,
            Math.min(1, 0.75 + (inside ? distance : -distance) / radius),
        );
        if (alpha > 0) {
            pixels.push(
                `<rect x="${horizontal}" y="${vertical}" width="1" height="1" fill-opacity="${alpha.toFixed(4)}"/>`,
            );
        }
    }
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" fill="black">${pixels.join("")}</svg>`;
const png = new Resvg(svg).render().asPng();
const directory = path.dirname(fileURLToPath(import.meta.url));
const output = path.resolve(
    directory,
    "../../gears/route-story/common/src/layer-specification/image-badge-sdf.ts",
);
fs.writeFileSync(
    output,
    `// Generated by scripts/app/generate-image-badge.ts.\nexport const IMAGE_BADGE_SDF_URI = "data:image/png;base64,${png.toString("base64")}";\n`,
);
