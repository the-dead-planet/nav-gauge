import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { Resvg } from '@resvg/resvg-js';
import { getOctagonalGeometry } from '../../ui/common/src/hud/octagonal-panel/geometry';
import { MAP_IMAGE_ANCHOR_SIDE } from '../../gears/route-story/common/src/tinkers/images';

// Pass NotoSans-Bold.ttf from notofonts/noto-fonts/hinted/ttf/NotoSans as the first argument.
const fontPath = process.argv[2];
assert(fontPath, 'Pass the path to NotoSans-Bold.ttf');
const labels = ['1', '2', '3', '4', '5', '6', '7', '8', '9', '9+'];
const glyphs: Record<string, string> = {};
for (const label of labels) {
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64"><text x="32" y="40" text-anchor="middle" font-family="Noto Sans" font-weight="700" font-size="22">${label}</text></svg>`;
    const converted = new Resvg(svg, {
        font: {
            fontFiles: [fontPath],
            loadSystemFonts: false,
        },
    }).toString();
    const paths = [...converted.matchAll(/<path\b[^>]*\bd="([^"]+)"/g)].map((match) => match[1]);
    assert(paths.length > 0 && !converted.includes('<text'), `Missing outlined glyphs for ${label}`);
    glyphs[label] = paths.join(' ');
}
const points = getOctagonalGeometry(40, 28, 'md').points.split(' ').map((point) => {
    const [horizontal, vertical] = point.split(',').map(Number);
    return `${horizontal + 12},${vertical + 18}`;
}).join(' ');
const output = path.resolve(__dirname, '../../gears/route-story/common/src/layer-specification/image-badge-glyphs.ts');
fs.writeFileSync(output, `// Generated by scripts/app/generate-image-badge.ts from Noto Sans Bold.\nexport const IMAGE_BADGE_POINTS = ${JSON.stringify(points)};\nexport const IMAGE_BADGE_GLYPHS: Record<string, string> = ${JSON.stringify(glyphs, null, 4)};\n`);

const hexagon = Array.from({ length: 6 }, (_value, index) => {
    const angle = (index * Math.PI) / 3 - Math.PI / 2;
    return [32 + MAP_IMAGE_ANCHOR_SIDE * 4 * Math.cos(angle), 32 + MAP_IMAGE_ANCHOR_SIDE * 4 * Math.sin(angle)];
});
const pixels: string[] = [];
for (let vertical = 0; vertical < 64; vertical++) {
    for (let horizontal = 0; horizontal < 64; horizontal++) {
        const x = horizontal + 0.5;
        const y = vertical + 0.5;
        let distance = Infinity;
        let inside = true;
        for (const [index, start] of hexagon.entries()) {
            const end = hexagon[(index + 1) % hexagon.length];
            const edgeX = end[0] - start[0];
            const edgeY = end[1] - start[1];
            const fraction = Math.max(0, Math.min(1, ((x - start[0]) * edgeX + (y - start[1]) * edgeY) / (edgeX * edgeX + edgeY * edgeY)));
            distance = Math.min(distance, Math.hypot(x - start[0] - fraction * edgeX, y - start[1] - fraction * edgeY));
            inside &&= edgeX * (y - start[1]) - edgeY * (x - start[0]) >= 0;
        }
        const alpha = Math.max(0, Math.min(1, 0.75 + (inside ? distance : -distance) / 8));
        if (alpha > 0) {
            pixels.push(`<rect x="${horizontal}" y="${vertical}" width="1" height="1" fill-opacity="${alpha.toFixed(4)}"/>`);
        }
    }
}
const anchor = new Resvg(`<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64">${pixels.join('')}</svg>`).render().asPng();
fs.writeFileSync(path.resolve(__dirname, '../../gears/route-story/common/src/layer-specification/image-marker-anchor.ts'),
    `// Generated by scripts/app/generate-image-badge.ts.\nexport const IMAGE_MARKER_ANCHOR_SDF_URI = "data:image/png;base64,${anchor.toString('base64')}";\n`);
